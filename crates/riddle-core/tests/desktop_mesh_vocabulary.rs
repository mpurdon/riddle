//! Writes the Mesh vocabulary the desktop's ⌘I insert menu offers, next to
//! the ts-rs bindings and by the same `cargo test -p riddle-core` run: the
//! fact names with their kinds, and the kept mail headers. ts-rs exports
//! types, not constants, so this test is the exporter; the desktop imports
//! the file rather than keeping a copy, and nothing can drift.

use riddle_core::{FactValue, Facts, KEPT_HEADERS};
use std::path::PathBuf;

#[test]
fn the_desktop_mesh_vocabulary_is_written_beside_the_bindings() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../apps/desktop/src/bindings/meshVocabulary.ts");
    let facts = Facts::default();
    let mut out = String::from(
        "// This file was generated by crates/riddle-core/tests/desktop_mesh_vocabulary.rs. Do not edit this file manually.\n\n/** Every fact a Mesh condition may name, with the kind of value it carries. */\nexport const MESH_FACTS = [\n",
    );
    for name in Facts::NAMES {
        let kind = match facts.get(name) {
            Some(FactValue::Bool(_)) => "bool",
            Some(FactValue::Number(_)) => "number",
            Some(FactValue::Text(_)) => "text",
            None => panic!("Facts::NAMES lists {name} but Facts::get does not know it"),
        };
        out.push_str(&format!("  {{ name: '{name}', kind: '{kind}' }},\n"));
    }
    out.push_str("] as const;\n\n/** The extra mail headers Sift keeps; any other `header <Name>` reads as empty text. */\nexport const MESH_HEADERS = [\n");
    for h in KEPT_HEADERS {
        out.push_str(&format!("  '{h}',\n"));
    }
    out.push_str("] as const;\n");
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    if current != out {
        std::fs::write(&path, out)
            .unwrap_or_else(|e| panic!("cannot write {}: {e}", path.display()));
    }
}
